// Writes src/lib/og-photo.ts: the profile photo as a small embedded image for the social cards.
// The cards are rendered on demand, where files from /public are not on disk. Run again if the photo changes:
//   node scripts/make-og-photo.cjs
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

(async () => {
  const jpeg = await sharp(path.join(__dirname, '../public/mario-perfil.jpg'))
    .resize(400, 400, { fit: 'cover', position: 'top' })
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  const source = `// Generated by scripts/make-og-photo.cjs from public/mario-perfil.jpg. Do not edit by hand.\nexport const ogPhoto = 'data:image/jpeg;base64,${jpeg.toString('base64')}';\n`;
  fs.writeFileSync(path.join(__dirname, '../src/lib/og-photo.ts'), source);
  console.log('og-photo.ts', Math.round(jpeg.length / 1024) + ' KB');
})();
